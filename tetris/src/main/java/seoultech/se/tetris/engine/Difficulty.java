package seoultech.se.tetris.engine;

/**
 * 게임 난이도
 *
 * <p>설정 화면에서 선택하며 일반 모드와 아이템 모드에 모두 적용한다.
 * 난이도에 따라 I형 블럭의 등장 가중치와 속도 증가량이 달라진다.
 * 구체적인 수치는 여기에서 가지지 않고 규칙을 계산하는 클래스가 가진다.
 *
 * <p><b>상수 이름은 저장 파일에 그대로 기록된다.</b> 이름을 바꾸면 이전에 저장한 기록과
 * 설정을 읽을 수 없으므로, 바꿔야 할 때는 불러오는 쪽에서도 변환 처리를 해야 한다.
 * 화면에 보여줄 이름은 화면을 표시하는 쪽에서 별도로 처리한다.
 */
public enum Difficulty {

    EASY,
    NORMAL,
    HARD;

    /**
     * 설정 파일에 난이도가 없을 때 사용하는 기본값
     *
     * <p>설정 저장과 불러오기, 초기화가 모두 이 값을 쓰도록 한 곳에 둔다.
     */
    public static final Difficulty DEFAULT = NORMAL;
}
