package seoultech.se.tetris.engine;

/**
 * 게임 모드
 *
 * <p>시작 메뉴에서 게임을 진행할 모드를 선택할 수 있다.
 *
 * <p><b>상수 이름은 저장 파일에 그대로 기록된다.</b> 이름을 바꾸면 이전에 저장한 기록을
 * 읽을 수 없으므로, 바꿔야 할 때는 불러오는 쪽에서도 변환 처리를 해야 한다.
 * 화면에 보여줄 이름은 화면을 표시하는 쪽에서 별도로 처리한다.
 */
public enum GameMode {

    /** 일반 모드 */
    NORMAL,

    /** 아이템 모드. 10줄을 지울 때마다 아이템이 등장한다. */
    ITEM
}
